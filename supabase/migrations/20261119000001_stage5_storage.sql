-- K DEALS Stage 5 Part A: private Supabase Storage buckets and policies.
-- Objects remain private; storefront delivery will use server-side signed URLs in Part B.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('product-images', 'product-images', false, 8388608, array['image/jpeg', 'image/png', 'image/webp']),
  ('product-documents', 'product-documents', false, 15728640, array['application/pdf']),
  ('site-banners', 'site-banners', false, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Storage paths are generated by the server in the form
-- {entity-uuid}/{asset-uuid}.{extension}; original filenames are metadata only.
-- Bucket-level limits and these checks are defense in depth, not a replacement
-- for server-side file-signature validation in the future upload route.
create policy product_images_admin_insert on storage.objects for insert to authenticated
  with check (
    bucket_id = 'product-images'
    and public.is_admin()
    and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp')
  );
create policy product_images_admin_select on storage.objects for select to authenticated
  using (bucket_id = 'product-images' and public.is_admin());
create policy product_images_admin_update on storage.objects for update to authenticated
  using (bucket_id = 'product-images' and public.is_admin())
  with check (bucket_id = 'product-images' and public.is_admin() and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp'));

create policy product_documents_admin_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'product-documents' and public.is_admin() and lower(storage.extension(name)) = 'pdf');
create policy product_documents_admin_select on storage.objects for select to authenticated
  using (bucket_id = 'product-documents' and public.is_admin());
create policy product_documents_admin_update on storage.objects for update to authenticated
  using (bucket_id = 'product-documents' and public.is_admin())
  with check (bucket_id = 'product-documents' and public.is_admin() and lower(storage.extension(name)) = 'pdf');

create policy site_banners_admin_insert on storage.objects for insert to authenticated
  with check (
    bucket_id = 'site-banners'
    and public.is_admin()
    and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp')
  );
create policy site_banners_admin_select on storage.objects for select to authenticated
  using (bucket_id = 'site-banners' and public.is_admin());
create policy site_banners_admin_update on storage.objects for update to authenticated
  using (bucket_id = 'site-banners' and public.is_admin())
  with check (bucket_id = 'site-banners' and public.is_admin() and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp'));

-- Referenced records cannot be removed through the ordinary admin path. A
-- future server-side media deletion action must first detach/reassign every
-- reference in the same transaction, then remove its object.
create or replace function public.storage_object_is_unreferenced(target_bucket text, target_path text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select not exists (
    select 1
    from public.media_assets m
    where m.storage_bucket = target_bucket
      and m.storage_path = target_path
      and (
        exists (select 1 from public.product_media pm where pm.media_asset_id = m.id)
        or exists (select 1 from public.product_documents pd where pd.media_asset_id = m.id)
        or exists (select 1 from public.categories c where c.image_asset_id = m.id)
        or exists (select 1 from public.product_variants pv where pv.image_asset_id = m.id)
        or exists (select 1 from public.banners b where b.desktop_image_asset_id = m.id or b.mobile_image_asset_id = m.id)
      )
  );
$$;

create policy product_images_admin_delete_unreferenced on storage.objects for delete to authenticated
  using (bucket_id = 'product-images' and public.is_admin() and public.storage_object_is_unreferenced(bucket_id, name));
create policy product_documents_admin_delete_unreferenced on storage.objects for delete to authenticated
  using (bucket_id = 'product-documents' and public.is_admin() and public.storage_object_is_unreferenced(bucket_id, name));
create policy site_banners_admin_delete_unreferenced on storage.objects for delete to authenticated
  using (bucket_id = 'site-banners' and public.is_admin() and public.storage_object_is_unreferenced(bucket_id, name));

grant execute on function public.storage_object_is_unreferenced(text, text) to authenticated;
